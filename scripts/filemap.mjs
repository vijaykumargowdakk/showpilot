// Writes FILEMAP.md: a tree of every file git tracks or would track (ignored files never appear).
// Paths only: sizes and times differ between checkouts and operating systems, so they would churn the file.
import { execFileSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'FILEMAP.md';

const listed = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const files = [...new Set(listed.split('\0').filter(Boolean))].filter(
  (f) => f !== OUTPUT && existsSync(path.join(root, f)),
);

const tree = new Map();
for (const file of files) {
  let node = tree;
  const parts = file.split('/');
  for (const dir of parts.slice(0, -1)) {
    if (!node.has(dir)) node.set(dir, new Map());
    node = node.get(dir);
  }
  node.set(parts.at(-1), null);
}

// Code-point order, not localeCompare, so every machine writes the same file whatever its locale.
const order = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const byName = (a, b) => order(a.toLowerCase(), b.toLowerCase()) || order(a, b);

const lines = [];
let dirs = 0;
function walk(node, depth) {
  const entries = [...node].sort(([a, ac], [b, bc]) => (ac ? 0 : 1) - (bc ? 0 : 1) || byName(a, b));
  for (const [name, children] of entries) {
    const indent = '  '.repeat(depth);
    if (children) {
      dirs++;
      lines.push(`${indent}- 📁 **${name}/**`);
      walk(children, depth + 1);
    } else {
      lines.push(`${indent}- 📄 ${name}`);
    }
  }
}
walk(tree, 0);

const header = [
  '# FILEMAP',
  '',
  '*Generated by `npm run filemap` (scripts/filemap.mjs). Do not edit by hand.*',
  '',
  `**${dirs} directories, ${files.length} files**`,
  '',
];
writeFileSync(path.join(root, OUTPUT), header.concat(lines).join('\n') + '\n');
console.log(`Wrote ${OUTPUT}: ${dirs} directories, ${files.length} files`);
