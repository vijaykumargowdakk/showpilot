// PostToolUse hook on creating a pull request. The GitHub tool can append an attribution footer to the description on
// GitHub's side, after the guard checked what the session sent, so the session is told to read the PR back and
// remove it (CLAUDE.md: no AI attribution in PR descriptions).
let data = '';
process.stdin.on('data', (chunk) => (data += chunk));
process.stdin.on('end', () => {
  let input;
  try {
    input = JSON.parse(data);
  } catch {
    return;
  }
  const number = String(input.tool_response?.url ?? JSON.stringify(input.tool_response ?? '')).match(/\/pull\/(\d+)/)?.[1];
  const which = number ? `PR #${number}` : 'the new PR';
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PostToolUse',
        additionalContext:
          `The GitHub tool may have appended an attribution footer (e.g. "Generated by Claude Code") to ${which}'s ` +
          'description on GitHub. Read the PR back now (pull_request_read, method get) and, if the description ends ' +
          'with such a footer, update it without the footer. CLAUDE.md allows no AI attribution in PR descriptions.',
      },
    }),
  );
});
